#!/usr/bin/env node
/**
 * Generates packages/figma-plugin/src/config/google-fonts.ts: every Google Fonts family with its available weights
 * (normal and italic). Figma Web offers the whole Google Fonts library, so Copy to Figma can keep a page's Google
 * font (Manrope, Jost, Cormorant Garamond…) instead of substituting it. The output is committed; nothing is fetched
 * at build or capture time. Re-run to refresh: node scripts/gen-google-fonts.mjs [metadata.json]
 * Source: https://fonts.google.com/metadata/fonts (public family metadata, no key).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(fileURLToPath(import.meta.url), '../..');
const OUT = join(repo, 'packages/figma-plugin/src/config/google-fonts.ts');

const text = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch('https://fonts.google.com/metadata/fonts')).text();
const data = JSON.parse(text.replace(/^\)\]\}'/, ''));

/** Bit k set = weight (k + 1) × 100 exists. */
const masks = (fonts) => {
  let normal = 0;
  let italic = 0;
  for (const key of Object.keys(fonts ?? {})) {
    const m = /^(\d00)(i?)$/.exec(key);
    if (!m) continue;
    const bit = 1 << (Number(m[1]) / 100 - 1);
    if (m[2]) italic |= bit;
    else normal |= bit;
  }
  return [normal, italic];
};

const rows = data.familyMetadataList
  .filter((f) => f.family && Object.keys(f.fonts ?? {}).length)
  .map((f) => [f.family, ...masks(f.fonts)])
  .filter(([, n, i]) => n || i)
  .sort((a, b) => (a[0] < b[0] ? -1 : 1));

const body = rows.map(([name, n, i]) => `${JSON.stringify(name)}:[${n},${i}]`).join(',');
writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/gen-google-fonts.mjs from https://fonts.google.com/metadata/fonts (${rows.length} families).
 * Family → [normal weights, italic weights] as bit masks: bit k = weight (k + 1) × 100. Do not edit by hand.
 */
// prettier-ignore
export const GOOGLE_FONTS: Record<string, [number, number]> = {${body}};
`,
);
console.log(`${rows.length} families → ${OUT}`);
