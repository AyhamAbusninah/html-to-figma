#!/usr/bin/env node
/**
 * Generates packages/figma-plugin/src/config/hair-spaces.ts: the width of a hair space (U+200A) in each Google
 * Fonts family, in em. Copy to Figma writes letter spacing as hair spaces (Figma's SVG import has no
 * letter-spacing) and Figma draws the font's own hair-space glyph, whose width varies by font (0.035–0.12 em).
 * Method: Google Fonts serves a font holding only "I" + U+200A (`text=`); headless Chromium measures it. Verified
 * against real Figma Web for 6 families within 0.001 em (spikes/figma-svg/README.md). Families at the 1/16 em
 * default (glyph missing or that width) are left out. Re-run: node scripts/gen-hair-spaces.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const repo = join(fileURLToPath(import.meta.url), '../..');
const OUT = join(repo, 'packages/figma-plugin/src/config/hair-spaces.ts');
const src = readFileSync(join(repo, 'packages/figma-plugin/src/config/google-fonts.ts'), 'utf8');
const families = [...src.matchAll(/"((?:[^"\\]|\\.)*)":\[(\d+),(\d+)\]/g)].map(([, f, n, i]) => {
  const mask = Number(n) || Number(i);
  // Regular (400) when it exists, else the lightest weight.
  const weight = mask & 8 ? 400 : (Math.log2(mask & -mask) + 1) * 100;
  return { family: JSON.parse(`"${f}"`), weight, italic: !Number(n) };
});
console.log(`${families.length} families`);

const DEFAULT = 0.0625;
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('data:text/html,<meta charset=utf-8>');
const result = {};
const BATCH = 24;
for (let i = 0; i < families.length; i += BATCH) {
  const batch = families.slice(i, i + BATCH);
  const widths = await page.evaluate(async (list) => {
    const c = document.createElement('canvas').getContext('2d');
    return Promise.all(
      list.map(async ({ family, weight, italic }, k) => {
        try {
          const axis = italic ? `ital,wght@1,${weight}` : `wght@${weight}`;
          const q = `family=${encodeURIComponent(family).replace(/%20/g, '+')}:${axis}&text=${encodeURIComponent('I ')}`;
          const css = await (await fetch(`https://fonts.googleapis.com/css2?${q}`)).text();
          const url = /url\(([^)]+)\)/.exec(css)?.[1];
          if (!url) return null;
          const name = `H${Math.random().toString(36).slice(2)}${k}`;
          const face = new FontFace(name, `url(${url})`);
          await face.load();
          document.fonts.add(face);
          c.font = `${italic ? 'italic ' : ''}1000px "${name}"`;
          const w = (c.measureText('I I').width - c.measureText('II').width) / 1000;
          document.fonts.delete(face);
          return Math.round(w * 10000) / 10000;
        } catch {
          return null;
        }
      }),
    );
  }, batch);
  batch.forEach((f, k) => {
    const w = widths[k];
    if (w != null && w > 0 && Math.abs(w - DEFAULT) > 0.001) result[f.family] = w;
  });
  process.stdout.write(`\r${Math.min(i + BATCH, families.length)}/${families.length}`);
}
await browser.close();
const names = Object.keys(result).sort();
writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/gen-hair-spaces.mjs (${names.length} of ${families.length} Google Fonts families differ from
 * the 1/16 em default). Width of a hair space (U+200A) in em, as Figma draws it. Do not edit by hand.
 */
export const DEFAULT_HAIR_SPACE_EM = ${DEFAULT};
// prettier-ignore
export const HAIR_SPACE_EM: Record<string, number> = {${names.map((n) => `${JSON.stringify(n)}:${result[n]}`).join(',')}};
`,
);
console.log(`\n${names.length} families → ${OUT}`);
