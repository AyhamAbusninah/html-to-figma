#!/usr/bin/env node
/**
 * Generates, from src/schema.ts:
 *   - capture.schema.json              published draft-07 schema
 *   - src/generated/validators.js      Ajv standalone validators (no eval at runtime → MV3 CSP-safe)
 *   - src/generated/validators.d.ts    their types
 *
 * `--check` regenerates in memory and fails if any committed file differs (CI guard against contract drift).
 * Run with Node ≥ 22.18 (native TypeScript type stripping): `node scripts/generate.ts [--check]`.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ajv } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { buildPublishedSchema, VALIDATOR_SCHEMAS } from '../src/schema.ts';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER =
  '// GENERATED by packages/schema/scripts/generate.ts from src/schema.ts. Do not edit.\n';

/** Deep copy without `description` keys (and without TypeBox symbol metadata). */
function stripDescriptions(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stripDescriptions);
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value))
      if (k !== 'description') out[k] = stripDescriptions(v);
    return out;
  }
  return value;
}

function generateValidators(): string {
  const ajv = new Ajv({ code: { source: true, esm: true }, allErrors: false, strict: true });
  const exportsMap: Record<string, string> = {};
  for (const [exportName, schema] of Object.entries(VALIDATOR_SCHEMAS)) {
    ajv.addSchema(stripDescriptions(schema) as object, exportName);
    exportsMap[exportName] = exportName;
  }
  return `${HEADER}/* eslint-disable */\n${standaloneCode(ajv, exportsMap)}\n`;
}

const DTS = `${HEADER}export interface AjvError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}
export type StandaloneValidator = ((data: unknown) => boolean) & { errors?: AjvError[] | null };
${Object.keys(VALIDATOR_SCHEMAS)
  .map((name) => `export declare const ${name}: StandaloneValidator;`)
  .join('\n')}
`;

const outputs: Record<string, string> = {
  'capture.schema.json': `${JSON.stringify(buildPublishedSchema(), null, 2)}\n`,
  'src/generated/validators.js': generateValidators(),
  'src/generated/validators.d.ts': DTS,
};

const check = process.argv.includes('--check');
let drift = 0;
for (const [rel, content] of Object.entries(outputs)) {
  const abs = join(pkgRoot, rel);
  if (check) {
    let current = '';
    try {
      current = readFileSync(abs, 'utf8');
    } catch {
      /* missing → drift */
    }
    if (current !== content) {
      drift++;
      console.error(
        `[schema:check] ${rel} is out of date. Run \`pnpm schema:generate\` and commit.`,
      );
    }
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`[schema:generate] wrote ${rel} (${content.length} bytes)`);
  }
}
if (check) {
  if (drift) process.exit(1);
  console.log('[schema:check] generated files are up to date');
}
